export function getKicks(type: PieceType, from: number, to: number): number[][] {
  if (type === 'O') return [[0, 0]];
  const key = `${from}>${to}`;
  if (type === 'I') return I_KICKS[key] || [[0, 0]];
  return JLSTZ_KICKS[key] || [[0, 0]];
}

export const PIECE_ORDER: PieceType[] = ['I', 'O', 'T', 'S', 'Z', 'J', 'L'];

export function makeBag(): PieceType[] {
  const bag = [...PIECE_ORDER];
  for (let i = bag.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [bag[i], bag[j]] = [bag[j], bag[i]];
  }
  return bag;
}
